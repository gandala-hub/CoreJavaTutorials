package com.core.tutorial.collection;

public class Laptop2  {
String make;
String model;
Double price;

Laptop2(String make, String model, Double price){
this.make = make;
this.model = model;
this.price = price;
}

public String getMake() {
	return make;
}

public String getModel() {
	return model;
}

public Double getPrice() {
	return price;
}
}
